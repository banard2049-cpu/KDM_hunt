const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
const monsters=JSON.parse(fs.readFileSync(path.join(root,'data/monsters.json')));
const flower=monsters.find(m=>m.id==='flower-knight');
const nodes={level:{value:'0'},startPositionHint:{style:{}},includeFan:{checked:false},addArcSurvivor:{checked:false},addScout:{checked:false}};
let saved;
const ctx=vm.createContext({selected:()=>flower,$:s=>nodes[s.slice(1)],fanCardCount:()=>0,deckFor:()=>[],shuffled:a=>a,render:()=>{},log:()=>{}});
ctx.autosave=()=>{saved=JSON.parse(JSON.stringify(ctx.S))};
vm.runInContext(script.slice(script.indexOf('function renderStartPositionHint('),script.indexOf('// Survivors advance one space')),ctx);
for(const [idx,party,monster] of [[0,2,8],[1,1,9],[2,0,10]]){
  nodes.level.value=String(idx);
  ctx.renderStartPositionHint();
  assert.equal(nodes.startPositionHint.style.display,'block');
  assert.ok(nodes.startPositionHint.textContent.includes('第 '+monster+' 格'));
  if(party===0)assert.ok(nodes.startPositionHint.textContent.includes('起始台'));
  ctx.begin();
  assert.equal(ctx.S.partyStart,party);
  assert.equal(ctx.S.partyPos,party);
  assert.equal(ctx.S.monsterPos,monster);
  assert.equal(saved.partyStart,party);
  assert.equal(ctx.S.drawn.length,0);
  assert.equal(ctx.S.track[5],'F');
}
ctx.selected=()=>monsters.find(m=>m.id==='white-lion');
ctx.renderStartPositionHint();
assert.equal(nodes.startPositionHint.style.display,'none');
assert.equal(ctx.startPositions(ctx.selected(),1).party,0);
console.log('Passed: Flower Knight levels 1/2/3 start at 2/1/0; monster 8/9/10; start/save and preview; White Lion unchanged.');
